using System.Globalization;
using System.IO.Compression;
using System.Text;

namespace TSharpVision.Samples.TVDemo;

/// <summary>Where a search hit came from, best first.</summary>
internal enum CharacterMatchSource
{
    /// <summary>The query is the code point itself (U+1F600, 0x1F600, 1F600).</summary>
    CodePoint,
    /// <summary>A word of TVDemo's own synonym list (<see cref="UnicodeCharacterNames.Synonyms"/>), not Unicode data.</summary>
    Synonym,
    /// <summary>The Unicode Name property (including algorithmic CJK, Tangut and Hangul names).</summary>
    Name,
    /// <summary>A formal Unicode name alias (NameAliases.txt): corrections, control names, abbreviations.</summary>
    Alias,
    /// <summary>The CLDR English short name (an emoji's common name), not a Unicode name.</summary>
    CldrName,
    /// <summary>A CLDR English keyword.</summary>
    CldrKeyword,
}

/// <summary>A ranked search result.</summary>
internal sealed record CharacterSearchResult(string Query, int[] Codes)
{
    public int Count => Codes.Length;
}

/// <summary>
/// Offline Unicode 16.0.0 character names, aliases and CLDR 46 English annotations for the Character Map, read from
/// the embedded <c>CharacterNames.txt.gz</c> (generated by the test suite's CharacterNameDataGenerator). Texts are
/// kept in a few large strings with offsets, not one object per character.
/// </summary>
internal sealed class UnicodeCharacterNames
{
    internal const string ResourceName = "TSharpVision.Samples.TVDemo.CharacterNames.txt.gz";
    internal const string UnicodeVersion = "16.0.0";
    internal const string CldrVersion = "46";

    /// <summary>
    /// Everyday words that are neither Unicode names nor CLDR keywords for all the characters people mean by them.
    /// Kept small and explicit; each hit is reported as <see cref="CharacterMatchSource.Synonym"/>.
    /// </summary>
    internal static readonly IReadOnlyDictionary<string, int[]> Synonyms = new Dictionary<string, int[]>(StringComparer.OrdinalIgnoreCase)
    {
        ["tick"] = [0x2713, 0x2714, 0x2611, 0x2705],
        ["checkmark"] = [0x2713, 0x2714, 0x2611, 0x2705],
        ["cross"] = [0x2717, 0x2718, 0x2612, 0x274C],
        ["smiley"] = [0x263A, 0x1F600, 0x1F642, 0x1F603],
        ["euro"] = [0x20AC],
        ["degree"] = [0x00B0, 0x2103, 0x2109],
        ["bullet"] = [0x2022, 0x25CF, 0x2219],
    };

    private static readonly Lazy<UnicodeCharacterNames> s_shared = new(() => new UnicodeCharacterNames(ReadEmbeddedText()));

    /// <summary>The database, loaded on first use.</summary>
    internal static UnicodeCharacterNames Shared => s_shared.Value;

    private readonly int[] _codes;
    private readonly string _names, _aliases, _cldrNames, _keywords;
    private readonly int[] _nameStart, _aliasStart, _cldrNameStart, _keywordStart;
    private readonly (int First, int Last, string Name)[] _blocks;
    private readonly (int First, int Last, string Prefix)[] _ranges;
    private readonly (int First, int Last) _hangul;

    internal UnicodeCharacterNames(string text)
    {
        var codes = new List<int>();
        var names = new StringBuilder(); var aliases = new StringBuilder(); var cldr = new StringBuilder(); var keywords = new StringBuilder();
        var nameStart = new List<int>(); var aliasStart = new List<int>(); var cldrStart = new List<int>(); var keywordStart = new List<int>();
        var blocks = new List<(int, int, string)>();
        var ranges = new List<(int, int, string)>();
        foreach (string line in text.Split('\n'))
        {
            if (line.Length < 2 || line[0] == '#') continue;
            string[] f = line.Split(';');
            switch (f[0])
            {
                case "B": blocks.Add((Hex(f[1]), Hex(f[2]), f[3])); break;
                case "R": ranges.Add((Hex(f[1]), Hex(f[2]), f[3])); break;
                case "H": _hangul = (Hex(f[1]), Hex(f[2])); break;
                case "C":
                    codes.Add(Hex(f[1]));
                    nameStart.Add(names.Length); names.Append(f[2]);
                    aliasStart.Add(aliases.Length); aliases.Append(f[3]);
                    cldrStart.Add(cldr.Length); cldr.Append(f[4]);
                    keywordStart.Add(keywords.Length); keywords.Append(f[5]);
                    break;
            }
        }
        nameStart.Add(names.Length); aliasStart.Add(aliases.Length); cldrStart.Add(cldr.Length); keywordStart.Add(keywords.Length);
        _codes = codes.ToArray();
        _names = names.ToString(); _aliases = aliases.ToString(); _cldrNames = cldr.ToString(); _keywords = keywords.ToString();
        _nameStart = nameStart.ToArray(); _aliasStart = aliasStart.ToArray(); _cldrNameStart = cldrStart.ToArray(); _keywordStart = keywordStart.ToArray();
        _blocks = blocks.ToArray();
        _ranges = ranges.ToArray();
    }

    /// <summary>Number of characters with an explicit name or alias in the database.</summary>
    internal int ExplicitEntries => _codes.Length;

    /// <summary>The decompressed embedded database text.</summary>
    internal static string ReadEmbeddedTextForTesting() => ReadEmbeddedText();

    private static string ReadEmbeddedText()
    {
        using Stream stream = typeof(UnicodeCharacterNames).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException($"Embedded resource '{ResourceName}' is missing.");
        using var gzip = new GZipStream(stream, CompressionMode.Decompress);
        using var reader = new StreamReader(gzip, new UTF8Encoding(false));
        return reader.ReadToEnd();
    }

    private static int Hex(string value) => int.Parse(value, NumberStyles.HexNumber, CultureInfo.InvariantCulture);

    private int IndexOf(int code) => Array.BinarySearch(_codes, code);

    private static ReadOnlySpan<char> Field(string blob, int[] starts, int index) =>
        blob.AsSpan(starts[index], starts[index + 1] - starts[index]);

    /// <summary>The Unicode Name property, or null (controls, unassigned, private use, surrogates).</summary>
    internal string? GetName(int code)
    {
        int i = IndexOf(code);
        if (i >= 0) return Field(_names, _nameStart, i) is { Length: > 0 } name ? name.ToString() : null;
        foreach (var (first, last, prefix) in _ranges)
            if (code >= first && code <= last) return prefix + code.ToString("X4", CultureInfo.InvariantCulture);
        return HangulName(code);
    }

    /// <summary>The name, else the first alias in angle brackets (control characters), else a placeholder label.</summary>
    internal string Label(int code)
    {
        if (GetName(code) is string name) return name;
        if (GetAliases(code) is [string alias, ..]) return "<" + alias + ">";
        if (!Rune.IsValid(code)) return "<surrogate>";
        return Rune.GetUnicodeCategory(new Rune(code)) switch
        {
            UnicodeCategory.PrivateUse => "<private use>",
            UnicodeCategory.OtherNotAssigned => "<unassigned>",
            _ => "<no name>",
        };
    }

    /// <summary>Formal aliases from NameAliases.txt.</summary>
    internal string[] GetAliases(int code) => Split(code, _aliases, _aliasStart);

    /// <summary>The CLDR English short name (not a Unicode name), or null.</summary>
    internal string? GetCldrName(int code)
    {
        int i = IndexOf(code);
        return i >= 0 && Field(_cldrNames, _cldrNameStart, i) is { Length: > 0 } name ? name.ToString() : null;
    }

    /// <summary>CLDR English keywords.</summary>
    internal string[] GetKeywords(int code) => Split(code, _keywords, _keywordStart);

    private string[] Split(int code, string blob, int[] starts)
    {
        int i = IndexOf(code);
        if (i < 0) return [];
        ReadOnlySpan<char> field = Field(blob, starts, i);
        return field.IsEmpty ? [] : field.ToString().Split('|');
    }

    /// <summary>The Unicode block, or null outside every block.</summary>
    internal string? GetBlock(int code)
    {
        int lo = 0, hi = _blocks.Length - 1;
        while (lo <= hi)
        {
            int mid = (lo + hi) / 2;
            if (code < _blocks[mid].First) hi = mid - 1;
            else if (code > _blocks[mid].Last) lo = mid + 1;
            else return _blocks[mid].Name;
        }
        return null;
    }

    private static readonly string[] JamoL = ["G", "GG", "N", "D", "DD", "R", "M", "B", "BB", "S", "SS", "", "J", "JJ", "C", "K", "T", "P", "H"];
    private static readonly string[] JamoV = ["A", "AE", "YA", "YAE", "EO", "E", "YEO", "YE", "O", "WA", "WAE", "OE", "YO", "U", "WEO", "WE", "WI", "YU", "EU", "YI", "I"];
    private static readonly string[] JamoT = ["", "G", "GG", "GS", "N", "NJ", "NH", "D", "L", "LG", "LM", "LB", "LS", "LT", "LP", "LH", "M", "B", "BS", "S", "SS", "NG", "J", "C", "K", "T", "P", "H"];

    /// <summary>The algorithmic name of a Hangul syllable (UAX #44 NR1), or null.</summary>
    internal static string? HangulName(int code)
    {
        int s = code - 0xAC00;
        if (s < 0 || s >= 11172) return null;
        return "HANGUL SYLLABLE " + JamoL[s / 588] + JamoV[s % 588 / 28] + JamoT[s % 28];
    }

    /// <summary>
    /// Ranked, case-insensitive search over names, aliases, CLDR short names and keywords, TVDemo synonyms and code
    /// points. Every word of the query must occur. Unassigned code points and surrogates never match. Results are
    /// ordered by how they matched (code point, synonym, exact name, name prefix, whole words, partial words, alias,
    /// CLDR name, CLDR keyword) and then by code point; nothing is truncated.
    /// </summary>
    internal CharacterSearchResult Search(string? query)
    {
        query = (query ?? string.Empty).Trim();
        if (query.Length == 0) return new CharacterSearchResult(query, []);
        string upper = query.ToUpperInvariant();
        string[] tokens = upper.Split([' ', '-', '_', ','], StringSplitOptions.RemoveEmptyEntries);
        var ranked = new List<(int Rank, int Code)>();
        var seen = new HashSet<int>();
        void Add(int rank, int code)
        {
            if (Assigned(code) && seen.Add(code)) ranked.Add((rank, code));
        }

        if (CharacterMapModel.TryParse(query, out int direct, out _) && (query.StartsWith("U+", StringComparison.OrdinalIgnoreCase)
            || query.StartsWith("0x", StringComparison.OrdinalIgnoreCase) || query.Length >= 4))
            Add(0, direct);
        if (Synonyms.TryGetValue(query, out int[]? synonyms))
            foreach (int code in synonyms) Add(1, code);

        // Ranks within a source: 0 equal, 1 prefix, 2 whole words, 3 parts of words.
        var candidates = new List<(int Rank, int Code)>();
        for (int i = 0; i < _codes.Length; i++)
        {
            int best = Better(int.MaxValue, 10, Match(Field(_names, _nameStart, i), upper, tokens));
            best = Better(best, 20, Match(Field(_aliases, _aliasStart, i), upper, tokens));
            best = Better(best, 30, Match(Field(_cldrNames, _cldrNameStart, i), upper, tokens));
            best = Better(best, 40, Match(Field(_keywords, _keywordStart, i), upper, tokens, acrossParts: true));
            if (best != int.MaxValue) candidates.Add((best, _codes[i]));
        }
        Span<char> name = stackalloc char[64];
        foreach (var (first, last, prefix) in _ranges)
        {
            if (!tokens.Any(t => prefix.Contains(t, StringComparison.OrdinalIgnoreCase))
                && !tokens.All(t => t.All(Uri.IsHexDigit))) continue;
            prefix.AsSpan().CopyTo(name);
            for (int code = first; code <= last; code++)
            {
                code.TryFormat(name[prefix.Length..], out int digits, "X4", CultureInfo.InvariantCulture);
                int m = Match(name[..(prefix.Length + digits)], upper, tokens);
                if (m >= 0) candidates.Add((10 + m, code));
            }
        }
        if (tokens.Any(t => "HANGUL SYLLABLE".Contains(t, StringComparison.OrdinalIgnoreCase)) || tokens.Length == 1)
            for (int code = _hangul.First; code <= _hangul.Last; code++)
            {
                int m = Match(HangulName(code), upper, tokens);
                if (m >= 0) candidates.Add((10 + m, code));
            }

        candidates.Sort();
        foreach (var (rank, code) in candidates) Add(rank, code);
        // Code point and synonym hits were added first and keep their place; the rest is in rank, code order.
        return new CharacterSearchResult(query, ranked.Select(r => r.Code).ToArray());
    }

    private static int Better(int best, int source, int match) => match < 0 ? best : Math.Min(best, source + match);

    private static bool Assigned(int code) =>
        Rune.IsValid(code) && Rune.GetUnicodeCategory(new Rune(code)) != UnicodeCategory.OtherNotAssigned;

    // 0: equal to the query; 1: starts with it; 2: every token is a whole word; 3: every token occurs; -1: no match.
    // Fields are '|'-separated lists (aliases, keywords) or one name; word boundaries are anything but letters/digits.
    // With acrossParts (keyword lists), the words of the query may come from different keywords.
    private static int Match(ReadOnlySpan<char> field, string query, string[] tokens, bool acrossParts = false)
    {
        if (field.IsEmpty) return -1;
        int best = -1;
        if (acrossParts)
        {
            bool all = true, words = true;
            foreach (string token in tokens)
            {
                if (!field.Contains(token, StringComparison.OrdinalIgnoreCase)) { all = false; break; }
                if (!IsWholeWord(field, token)) words = false;
            }
            if (all) best = words ? 2 : 3;
        }
        foreach (Range part in field.Split('|'))
        {
            ReadOnlySpan<char> text = field[part];
            int m;
            if (text.Equals(query, StringComparison.OrdinalIgnoreCase)) m = 0;
            else if (text.StartsWith(query, StringComparison.OrdinalIgnoreCase)) m = 1;
            else
            {
                bool all = true, words = true;
                foreach (string token in tokens)
                {
                    int at = text.IndexOf(token, StringComparison.OrdinalIgnoreCase);
                    if (at < 0) { all = false; break; }
                    if (!IsWholeWord(text, token)) words = false;
                }
                if (!all) continue;
                m = words ? 2 : 3;
            }
            if (best < 0 || m < best) best = m;
            if (best == 0) break;
        }
        return best;
    }

    private static bool IsWholeWord(ReadOnlySpan<char> text, string token)
    {
        for (int at = text.IndexOf(token, StringComparison.OrdinalIgnoreCase); at >= 0;)
        {
            int end = at + token.Length;
            bool start = at == 0 || !char.IsLetterOrDigit(text[at - 1]);
            bool stop = end == text.Length || !char.IsLetterOrDigit(text[end]);
            if (start && stop) return true;
            int next = text[(at + 1)..].IndexOf(token, StringComparison.OrdinalIgnoreCase);
            at = next < 0 ? -1 : at + 1 + next;
        }
        return false;
    }
}
