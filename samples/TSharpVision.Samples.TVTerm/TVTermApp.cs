    private void OpenSessionDemo(SessionKind kind)
    {
        if (kind != SessionKind.Pipe && !PtyAvailability.IsAnyPtySupported)
        {
            NotImplementedMsg("PTY is unavailable on this platform. Use the pipe demonstration.");
            return;
        }
        bool windows = OperatingSystem.IsWindows();
        var spec = kind switch
        {
            SessionKind.Pipe => new SessionSpec { Kind = kind, FileName = "dotnet", Arguments = "--info" },
            SessionKind.Shell => new SessionSpec { Kind = kind, FileName = DefaultShell(), RawSession = true },
            _ => new SessionSpec { Kind = kind, FileName = windows ? "cmd.exe" : "sh",
                Arguments = windows ? "/c echo Hello from ConPTY" : "-c \"echo Hello from POSIX PTY\"" }
        };
        var win = OpenWindow($"{kind} Demo");
        WireDemoCommandLoop(win);
        win.Terminal.WriteLine("Session menu: interrupt, restart or kill. Shell: type exit to return to local input.");
        win.StartSession(spec);
    }

    private void OpenScriptedDemo(string title, System.Action<InMemoryTerminalSession> script)
    {
        var win = OpenWindow(title);
        win.Terminal.InputEnabled = false;
        // Use the embedded in-memory session via the EmitBanner indirection:
        // run the script directly on a fresh InMemorySession would not show
        // up because TTerminal is attached to the window's own _memSession.
        // Instead drive the embedded session by writing via TTerminal.Write.
        ScriptToTerminal(win.Terminal, script);
    }

    private static void ScriptToTerminal(TTerminal term, System.Action<InMemoryTerminalSession> script)
    {
        // Run the script through a transient session whose output is replayed
        // into the terminal. This keeps the demo scripts session-typed.
        var transient = new InMemoryTerminalSession();
        transient.OutputReceived += (_, e) => term.Write(e.Text);
        transient.StartAsync().GetAwaiter().GetResult();
        script(transient);
        transient.StopAsync().GetAwaiter().GetResult();
        transient.Dispose();
    }

