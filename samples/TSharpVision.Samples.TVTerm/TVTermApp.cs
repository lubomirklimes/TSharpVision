    public override THelpFile GetHelpFile()
    {
        EnsureHelpFile();
        return _helpFile!;
    }

    private void EnsureHelpFile()
    {
        if (_helpFile != null) return;
        THelpFile.RegisterStreamableTypes();
        string hlpPath = Path.Combine(System.AppContext.BaseDirectory, "Assets", "Help", "TVTERM.HLP");
        if (!File.Exists(hlpPath)) return;
        _helpStream = new Fpstream(hlpPath);
        _helpFile = new THelpFile(
            _helpStream,
            new HelpV1LoadOptions { LegacyEncoding = LegacyTextEncodings.Cp437 });
    }

    public override void ShutDown()
    {
        _helpStream?.Close();
        _helpStream = null;
        _helpFile = null;
        base.ShutDown();
    }

    // ------------------------------------------------------------------
    // Event dispatch
    // ------------------------------------------------------------------

    public override void HandleEvent(ref TEvent ev)
    {
        base.HandleEvent(ref ev);
        if (ev.What != Events.evCommand) return;

        ushort cmd = ev.message.command;
        switch (cmd)
        {
            case Commands.cmNewTerminal:      OpenNewTerminal(); break;
            case Commands.cmNewFakeTerminal:  OpenFakeTerminal(); break;
            case Commands.cmRunCommand:       OpenRunCommandDialog(); break;
            case Commands.cmOpenLog:          OpenLogFile(); break;
            case Commands.cmSaveOutput:       SaveOutput(); break;

            case Commands.cmCopy:             DoCopy(); break;
            case Commands.cmPaste:            DoPaste(); break;
            case Commands.cmSelectAll:        DoSelectAll(); break;
            case Commands.cmClearSelection:   DoClearSelection(); break;
            case Commands.cmFind:             DoFind(); break;
            case Commands.cmFindNext:         DoFindNext(); break;

            case Commands.cmClearScreen:      WithTerm(t => t.Clear()); break;
            case Commands.cmScrollTop:        WithTerm(t => t.ScrollToTop()); break;
            case Commands.cmScrollBottom:     WithTerm(t => t.ScrollToBottom()); break;
            case Commands.cmToggleWrap:       NotImplementedMsg("Line wrapping is always on; toggle support requires core API changes."); break;
            case Commands.cmToggleAnsi:       DoToggleAnsi(); break;

            case Commands.cmInterrupt:        WithWindow(w => w.Interrupt()); break;
            case Commands.cmRestart:          WithWindow(w => w.RestartExternalSession()); break;
            case Commands.cmSendEof:          WithWindow(w => w.SendEof()); break;
            case Commands.cmKill:             WithWindow(w => w.StopExternalSession()); break;

            case Commands.cmKeyInspector:     OpenKeyInspector(); break;
            case Commands.cmUnicodeDemo:      OpenScriptedDemo("Unicode Demo", TerminalDemos.RunUnicodeDemo); break;
            case Commands.cmAnsiDemo:         OpenScriptedDemo("ANSI Demo",    TerminalDemos.RunAnsiDemo); break;
            case Commands.cmPerfDemo:         OpenScriptedDemo("Performance Demo", s => TerminalDemos.RunPerformanceDemo(s, 64)); break;
            case Commands.cmSelectionDemo:    OpenSelectionDemo(); break;
            case Commands.cmPipeDemo:         OpenSessionDemo(SessionKind.Pipe); break;
            case Commands.cmPtyDemo:          OpenSessionDemo(SessionKind.Pty); break;
            case Commands.cmShellDemo:        OpenSessionDemo(SessionKind.Shell); break;

            case Commands.cmTerminalSettings: TerminalSettingsDialog.ShowDialog(DeskTop!, _config); break;
            case Commands.cmUiColors:         OpenUiColors(); break;
            case Commands.cmColorMapping:
                ColorMappingDialog.ShowDialog(DeskTop!, _config);
                ApplyColorMapToAllTerminals();
                break;
            case Commands.cmKeyboardMapping:  KeyboardMappingDialog.ShowDialog(DeskTop!, _config); break;

            case Commands.cmHelpContents:     OpenHelp(); break;
            case Commands.cmAbout:            AboutDialog.ShowDialog(DeskTop!); break;

            default: return;
        }
        ClearEvent(ref ev);
    }

