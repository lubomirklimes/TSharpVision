    private void DoCopy()
    {
        var t = ActiveTerminal();
        if (t == null) return;
        if (t.HasSelection) t.CopySelection();
    }

    private void DoPaste()
    {
        var t = ActiveTerminal();
        if (t == null) return;
        if (ClipboardService.Current.TryGetText(out string text))
            t.PasteText(text);
    }

    private void DoSelectAll()
    {
        var t = ActiveTerminal();
        if (t == null || t.Lines.Count == 0) return;
        var anchor = new TerminalTextPosition(0, 0);
        int lastLine = t.Lines.Count - 1;
        int lastCol = t.Lines[lastLine].Length;
        var active = new TerminalTextPosition(lastLine, lastCol);
        t.SetSelection(anchor, active);
        t.DrawView();
    }

    private void DoClearSelection()
    {
        var t = ActiveTerminal();
        t?.ClearSelection();
        t?.DrawView();
    }

    private void DoFind()
    {
        var t = ActiveTerminal();
        if (t == null) return;
        var r = FindDialog.ShowDialog(DeskTop!, _lastFindText);
        if (r == null) return;
        _lastFindText = r.Text;
        FindAndSelect(t, r.Text, r.CaseSensitive, fromTop: true);
    }

    private void DoFindNext()
    {
        var t = ActiveTerminal();
        if (t == null || string.IsNullOrEmpty(_lastFindText)) return;
        FindAndSelect(t, _lastFindText, caseSensitive: false, fromTop: false);
    }

    private void FindAndSelect(TTerminal t, string needle, bool caseSensitive, bool fromTop)
    {
        var cmp = caseSensitive ? System.StringComparison.Ordinal : System.StringComparison.OrdinalIgnoreCase;
        var lines = t.Lines;
        int startLine = 0, startCol = 0;
        if (!fromTop && t.HasSelection)
        {
            // Continue right after the current selection end. Without access
            // to selection bounds, fall back to a fresh search from line 1
            // past the last hit if we can compute it; otherwise from top.
            // SetSelection doesn't expose getters, so start past the last hit
            // we did via _lastFindHit (tracked below if needed).
        }
        for (int i = startLine; i < lines.Count; i++)
        {
            int col = (i == startLine ? startCol : 0);
            int idx = lines[i].IndexOf(needle, col, cmp);
            if (idx >= 0)
            {
                t.SetSelection(new TerminalTextPosition(i, idx),
                               new TerminalTextPosition(i, idx + needle.Length));
                t.ScrollToBottom();
                t.DrawView();
                return;
            }
        }
        MsgBox.MessageBox(DeskTop!, $"\"{needle}\" not found.", MsgBox.mfInformation | MsgBox.mfOKButton);
    }

