    private TTerminalWindow? ActiveTerminalWindow()
    {
        var v = DeskTop?.current;
        while (v != null)
        {
            if (v is TTerminalWindow ttw) return ttw;
            // walk owner chain — not strictly needed; current usually is the window
            break;
        }
        return null;
    }

    private TTerminal? ActiveTerminal() => ActiveTerminalWindow()?.Terminal;

    private void WithTerm(System.Action<TTerminal> action)
    {
        var t = ActiveTerminal();
        if (t != null) action(t);
    }

    private void WithWindow(System.Action<TTerminalWindow> action)
    {
        var w = ActiveTerminalWindow();
        if (w != null) action(w);
    }

    private void NotImplementedMsg(string msg)
    {
        if (DeskTop != null)
            MsgBox.MessageBox(DeskTop, msg, MsgBox.mfInformation | MsgBox.mfOKButton);
    }

    // ------------------------------------------------------------------
    // Options / UI Colors — TColorDialog backed by the live TProgram palette
    // ------------------------------------------------------------------

    private void OpenUiColors()
    {
        if (DeskTop == null) return;

        // Clone the live TProgram palette so TColorDialog edits a copy.
        // TColorItem indices are 1-based positions in TProgram.cpColor:
        //   1           → TBackground (desktop fill)
        //   2, 4        → TMenuView normal / selected item
        //   8, 9        → TWindow (blue) frame / title
        //   32, 34      → TDialog frame / title
        //   41, 45      → TButton normal / default
        var pal = GetPalette().Clone();

        var groups =
            new TColorGroup("Desktop",
                new TColorItem("Background", 1)) +
            new TColorGroup("Menu",
                new TColorItem("Normal",    2) +
                new TColorItem("Selected",  4)) +
            new TColorGroup("Window",
                new TColorItem("Frame",  8) +
                new TColorItem("Title",  9)) +
            new TColorGroup("Dialog",
                new TColorItem("Frame", 32) +
                new TColorItem("Title", 34)) +
            new TColorGroup("Button",
                new TColorItem("Normal",  41) +
                new TColorItem("Default", 45));

        var dlg = new TColorDialog(pal, groups);
        if (ValidView(dlg) == null) return;

        if (DeskTop.ExecView(dlg) == Views.cmOK)
        {
            var live = GetPalette();
            TPalette? editedPalette = dlg.Pal;
            if (editedPalette == null) return;
            System.Array.Copy(editedPalette.Data, live.Data,
                System.Math.Min(editedPalette.Data.Length, live.Data.Length));
            DrawView();
        }
    }

    private string DefaultShell()
    {
        if (!string.IsNullOrWhiteSpace(_config.DefaultShell)) return _config.DefaultShell;
        return System.OperatingSystem.IsWindows()
            ? "cmd.exe"
            : (System.Environment.GetEnvironmentVariable("SHELL") ?? "/bin/sh");
    }

    // ------------------------------------------------------------------
    // Built-in demo command loop for InMemory terminals
    // ------------------------------------------------------------------

    private static void WireDemoCommandLoop(TTerminalWindow win)
    {
        var term = win.Terminal;
        term.CommandSubmitted += (_, e) =>
        {
            string cmd = e.Command.Trim();
            if (cmd.Length == 0) return;
            if (cmd.Equals("help", System.StringComparison.OrdinalIgnoreCase))
            {
                term.WriteLine("Built-in commands:");
                term.WriteLine("  help              show this help");
                term.WriteLine("  echo <text>       write text to the terminal");
                term.WriteLine("  clear | cls       clear the terminal");
                term.WriteLine("  size              show terminal size");
                term.WriteLine("Use the menu (F10) for Session/Tools/Options.");
            }
            else if (cmd.Equals("clear", System.StringComparison.OrdinalIgnoreCase) ||
                     cmd.Equals("cls",   System.StringComparison.OrdinalIgnoreCase))
            {
                term.Clear();
            }
            else if (cmd.Equals("size", System.StringComparison.OrdinalIgnoreCase))
            {
                var ts = term.TerminalSize;
                term.WriteLine($"Terminal size: {ts.Columns} x {ts.Rows}");
            }
            else if (cmd.StartsWith("echo ", System.StringComparison.OrdinalIgnoreCase))
            {
                term.WriteLine(cmd.Substring(5));
            }
            else
            {
                term.WriteLine($"Unknown command: {cmd}");
            }
        };
    }
