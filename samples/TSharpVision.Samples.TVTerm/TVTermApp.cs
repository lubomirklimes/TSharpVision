    private TRect NewWindowRect()
    {
        int x = 2 + (_windowCascade % 6);
        int y = 1 + (_windowCascade % 5);
        _windowCascade++;
        int w = System.Math.Min(80, DeskTop!.size.x - x - 1);
        int h = System.Math.Min(22, DeskTop!.size.y - y - 1);
        return new TRect(x, y, x + w, y + h);
    }

    private TTerminalWindow OpenWindow(string title)
    {
        var win = new TTerminalWindow(NewWindowRect(), title, Views.wnNoNumber);
        DeskTop!.Insert(win);
        ApplyColorMap(win.Terminal);
        return win;
    }

    private void ApplyColorMap(TTerminal term)
    {
        if (_config.ColorMap is { Length: >= 16 } map)
            term.ApplyColorMap(map);
    }

    private void ApplyColorMapToAllTerminals()
    {
        DeskTop?.ForEachView(v =>
        {
            if (v is TTerminalWindow tw)
                ApplyColorMap(tw.Terminal);
        });
    }

    private void OpenNewTerminal()
    {
        var win = OpenWindow("Terminal");
        win.EmitBanner("Local command terminal. Type 'help' for built-in demo commands.\n");
        win.EmitBanner("Use Session → Restart to relaunch the last external session.\n\n");
        WireDemoCommandLoop(win);

        // If user configured a default external session, start it.
        switch (_config.DefaultSessionMode)
        {
            case DefaultSessionMode.Pty when PtyAvailability.IsAnyPtySupported:
                win.StartSession(new SessionSpec
                {
                    Kind = SessionKind.Shell,
                    FileName = DefaultShell(),
                    Arguments = string.Empty,
                    RawSession = true,
                });
                break;
            case DefaultSessionMode.Fake:
                win.StartSession(new SessionSpec { Kind = SessionKind.Fake });
                break;
            // Pipe / InMemory: leave the InMemory command loop running.
        }
    }

    private void OpenFakeTerminal()
    {
        var win = OpenWindow("Fake Terminal");
        win.EmitBanner("FakePtyTerminalSession — deterministic, no real process.\n");
        WireDemoCommandLoop(win);
        win.StartSession(new SessionSpec { Kind = SessionKind.Fake });
    }

    private void OpenRunCommandDialog()
    {
        if (DeskTop == null) return;
        var r = RunCommandDialog.ShowDialog(DeskTop);
        if (r == null) return;

        var win = OpenWindow($"Run: {r.FileName}");
        win.EmitBanner($"Starting {r.Kind}: {r.FileName} {r.Arguments}\n");
        win.StartSession(new SessionSpec
        {
            Kind = r.Kind,
            FileName = r.FileName,
            Arguments = r.Arguments,
            WorkingDirectory = r.WorkingDirectory,
            RawSession = false,
        });
    }

    private void OpenLogFile()
    {
        if (DeskTop == null) return;
        var fd = new TFileDialog("*.*", "Open Log File", "~F~ile name",
                                 FileDialogOptions.fdOpenButton, 0);
        if (ValidView(fd) == null) return;
        ushort res = DeskTop.ExecView(fd);
        if (res != Views.cmOK) return;
        fd.GetData(out string path);
        if (string.IsNullOrWhiteSpace(path) || !File.Exists(path))
        {
            MsgBox.MessageBox(DeskTop, $"File not found: {path}", MsgBox.mfError | MsgBox.mfOKButton);
            return;
        }

        var win = OpenWindow(Path.GetFileName(path));
        try
        {
            string text = File.ReadAllText(path);
            win.EmitBanner(text);
            if (!text.EndsWith("\n")) win.EmitBanner("\n");
            win.EmitBanner($"-- end of {Path.GetFileName(path)} --\n");
        }
        catch (System.Exception ex)
        {
            win.EmitBanner($"[Error reading file] {ex.Message}\n");
        }
        win.Terminal.InputEnabled = false;
    }

    private void SaveOutput()
    {
        if (DeskTop == null) return;
        var term = ActiveTerminal();
        if (term == null)
        {
            MsgBox.MessageBox(DeskTop, "No active terminal window.", MsgBox.mfInformation | MsgBox.mfOKButton);
            return;
        }
        var fd = new TFileDialog("*.txt", "Save Output", "~F~ile name",
                                 FileDialogOptions.fdOKButton, 0);
        if (ValidView(fd) == null) return;
        ushort res = DeskTop.ExecView(fd);
        if (res != Views.cmOK) return;
        fd.GetData(out string path);
        if (string.IsNullOrWhiteSpace(path)) return;
        try
        {
            File.WriteAllLines(path, term.Lines);
            MsgBox.MessageBox(DeskTop, $"Saved {term.Lines.Count} lines.", MsgBox.mfInformation | MsgBox.mfOKButton);
        }
        catch (System.Exception ex)
        {
            MsgBox.MessageBox(DeskTop, $"Save failed: {ex.Message}", MsgBox.mfError | MsgBox.mfOKButton);
        }
    }

